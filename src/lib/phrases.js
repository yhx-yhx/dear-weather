export function phrasePool(scene, overrides = {}) {
  const custom = overrides && overrides[scene]
  if (Array.isArray(custom) && custom.filter(Boolean).length) {
    return custom.filter(Boolean)
  }
  return DEFAULT_PHRASES[scene] || DEFAULT_PHRASES.daily
}

export function dailyLine(date = new Date(), overrides = {}) {
  const custom = overrides && overrides.daily
  const pool = Array.isArray(custom) && custom.filter(Boolean).length ? custom.filter(Boolean) : DAILY_LINES
  const day = date.getDay()
  return pool[day % pool.length]
}
